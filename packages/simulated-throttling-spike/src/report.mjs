import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { median, summarize } from './evaluate-summary.mjs';
import { METRICS, RESULTS } from './paths.mjs';

/**
 * Writes `results/<set>.md` from `results/<set>.json`: per target, the median over its runs of
 * each metric under DevTools throttling, without throttling, and from Lantern in each
 * configuration.
 *
 * Usage: node report.mjs [--set fixture] [--configurations root+chains+paint,all]
 */

const { values } = parseArgs({
  options: {
    set: { type: 'string', default: 'fixture' },
    configurations: { type: 'string' },
  },
});

const { rows } = JSON.parse(
  readFileSync(join(RESULTS, `${values.set}.json`), 'utf8'),
);
const evaluated = Object.keys(rows[0]?.lantern ?? {});
const configurations = values.configurations?.split(',') ?? evaluated;
const unknown = configurations.filter((name) => !evaluated.includes(name));
if (unknown.length) {
  throw new Error(
    `${values.set}.json has no configuration ${unknown.join(', ')}. It has: ${evaluated.join(', ')}`,
  );
}

const lines = [
  `# Results: ${values.set}`,
  '',
  'Generated by `report.mjs` from `' +
    values.set +
    '.json`. Times are in ms from the start of the soft navigation, the median of the runs. Lantern errors are relative to DevTools throttling.',
  '',
  '## Summary',
  '',
  'Every configuration, over every run of every target. The tables per target below show the main ones.',
  '',
  summarize(rows, evaluated),
  '',
];

for (const target of new Set(rows.map((row) => row.target))) {
  const runs = rows.filter((row) => row.target === target);
  lines.push(`## ${target}`, '');
  lines.push(`${runs.length} runs.`, '');
  lines.push(
    `| | ${METRICS.map(({ id }) => id.toUpperCase()).join(' | ')} |`,
    `| --- | ${METRICS.map(() => '---:').join(' | ')} |`,
  );
  const reference = medians(runs.map((run) => run.reference));
  lines.push(
    `| DevTools throttling | ${METRICS.map(({ id }) => ms(reference[id])).join(' | ')} |`,
  );
  const observed = medians(runs.map((run) => run.observed));
  lines.push(
    `| Recorded without throttling | ${METRICS.map(({ id }) => ms(observed[id])).join(' | ')} |`,
  );
  for (const configuration of configurations) {
    const lantern = medians(
      runs.map((run) => run.lantern[configuration] ?? {}),
    );
    lines.push(
      `| Lantern, ${configuration} | ${METRICS.map(({ id }) => {
        // The median is over the runs that computed a value, so the runs that did not are
        // counted next to it.
        const errors = runs
          .filter((run) => typeof run.lantern[configuration]?.[id] !== 'number')
          .map((run) => run.errors[configuration]?.[id] ?? 'no value');
        const failed = errors.length
          ? `${errors.length} of ${runs.length} failed: ${[...new Set(errors)].map((error) => `\`${error}\``).join(', ')}`
          : '';
        if (lantern[id] === null) return failed;
        return `${ms(lantern[id])}${relative(lantern[id], reference[id])}${failed ? ` (${failed})` : ''}`;
      }).join(' | ')} |`,
    );
  }
  lines.push('');
}

writeFileSync(join(RESULTS, `${values.set}.md`), lines.join('\n'));

/** Median per metric of the values that are numbers. */
function medians(list) {
  return Object.fromEntries(
    METRICS.map(({ id }) => {
      const numbers = list
        .map((item) => item[id])
        .filter((value) => typeof value === 'number');
      return [id, numbers.length ? median(numbers) : null];
    }),
  );
}

function ms(value) {
  return value === null || value === undefined
    ? '—'
    : String(Math.round(value));
}

function relative(value, reference) {
  if (!reference) return '';
  const percent = Math.round(((value - reference) / reference) * 100);
  return ` (${percent > 0 ? '+' : ''}${percent} %)`;
}
